import express from 'express';
import request from 'supertest';
import fs from 'node:fs/promises';
import path from 'node:path';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { MAX_USER_PHOTO_BYTES } from '../shared/user-photo';
const mocks = vi.hoisted(() => ({ list: vi.fn(), create: vi.fn(), detail: vi.fn(), rename: vi.fn(), updateProfile: vi.fn(), addParticipants: vi.fn(),
  removeParticipant: vi.fn(), leave: vi.fn(), memberIds: vi.fn(), messages: vi.fn(), send: vi.fn(), markRead: vi.fn(), attachment: vi.fn(), publish: vi.fn() }));
vi.mock('../server/middleware/auth.middleware', () => ({ requireAuth: (req: any, _res: any, next: () => void) => { req.user = { id: 7, module: 'sales' }; next(); } }));
vi.mock('../server/realtime/realtime-hub', () => ({ publishRealtimeEvent: mocks.publish }));
vi.mock('../server/lib/logger', () => ({ logger: { error: vi.fn() } }));
import { createChatGroupRouter } from '../server/routes/chat-groups.routes';
import { chatGroupPhotoPath } from '../server/middleware/chat-group-photo.middleware';
const app = express(); app.use(express.json()); app.use('/api/chat-groups', createChatGroupRouter(mocks));
const directory = path.dirname(chatGroupPhotoPath('aaaaaaaaaaaaaaaaaaaaa')!);
const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a2nUAAAAASUVORK5CYII=', 'base64');
let group: { id: number; name: string; avatarUrl: string | null; canManage: boolean };
let before: string[];
beforeEach(async () => {
  vi.resetAllMocks(); await fs.mkdir(directory, { recursive: true }); before = await fs.readdir(directory);
  group = { id: 4, name: 'Team', avatarUrl: null, canManage: true };
  mocks.memberIds.mockResolvedValue([7, 8]); mocks.detail.mockImplementation(async () => ({ ...group }));
  mocks.updateProfile.mockImplementation(async (_id, _actor, _administrator, input) => {
    const previousAvatarUrl = group.avatarUrl; Object.assign(group, input); return { audienceUserIds: [7, 8], previousAvatarUrl };
  });
});
afterEach(async () => {
  // Only delete bytes generated by this suite, never existing local uploads or retained backups.
  const ids = mocks.updateProfile.mock.calls.flatMap(([, , , input]) => typeof input.avatarUrl === 'string' ? [input.avatarUrl.split('/').at(-1)!] : []);
  await Promise.all([...new Set(ids)].flatMap(id => [chatGroupPhotoPath(id)!, path.resolve('uploads/.retained/group-photos', id)])
    .map(file => fs.unlink(file).catch((error: NodeJS.ErrnoException) => { if (error.code !== 'ENOENT') throw error; })));
});
const upload = (bytes = png, profile = { name: 'New team' }) => request(app).patch('/api/chat-groups/4').field('profile', JSON.stringify(profile)).attach('photo', bytes, { filename: 'photo.png', contentType: 'image/png' });
describe('private group profile photos', () => {
  it('stores name and photo atomically and announces the current audience', async () => {
    await upload().expect(200);
    expect(mocks.updateProfile).toHaveBeenCalledWith(4, 7, false, { name: 'New team', avatarUrl: expect.stringMatching(/^\/api\/chat-groups\/4\/photos\/[A-Za-z0-9_-]{21}$/) });
    const result = await request(app).get(group.avatarUrl!); expect(result.status).toBe(200);
    expect(result.headers['content-type']).toContain('image/png'); expect(result.headers['cache-control']).toBe('private, no-store');
    expect(result.headers['x-content-type-options']).toBe('nosniff');
    expect(mocks.publish).toHaveBeenCalledWith({ type: 'GROUP_CHAT_UPDATED', data: { groupId: 4 }, audienceUserIds: [7, 8] });
  });
  it('rejects ordinary members before writing an uploaded file', async () => {
    group.canManage = false; await upload().expect(403);
    expect(await fs.readdir(directory)).toEqual(before); expect(mocks.updateProfile).not.toHaveBeenCalled();
  });
  it('does not expose files to a guessed group or a removed member', async () => {
    await upload().expect(200); const url = group.avatarUrl!;
    await request(app).get(url.replace('/4/', '/5/')).expect(404);
    mocks.memberIds.mockResolvedValue(null); await request(app).get(url).expect(404);
  });
  it('retains replaced committed bytes for backups and revokes the previous photo URL', async () => {
    await upload().expect(200); const oldUrl = group.avatarUrl!; const oldId = oldUrl.split('/').at(-1)!;
    await upload().expect(200); expect(group.avatarUrl).not.toBe(oldUrl);
    await request(app).get(oldUrl).expect(404); await expect(fs.stat(chatGroupPhotoPath(oldId)!)).rejects.toMatchObject({ code: 'ENOENT' });
    expect(await fs.readFile(path.resolve('uploads/.retained/group-photos', oldId))).toEqual(png);
  });
  it('clears the database reference before retaining removed bytes', async () => {
    await upload().expect(200); const oldUrl = group.avatarUrl!;
    await request(app).patch('/api/chat-groups/4').send({ name: 'Team', removePhoto: true }).expect(200);
    expect(group.avatarUrl).toBeNull(); await request(app).get(oldUrl).expect(404);
  });
  it('rejects fake image MIME types and deletes the staged file', async () => {
    const response = await upload(Buffer.from('<svg><script>alert(1)</script></svg>'));
    expect(response.status).toBe(400); expect(response.body.error).toBe('profilePhotoTypeUnsupported');
    expect(await fs.readdir(directory)).toEqual(before); expect(mocks.updateProfile).not.toHaveBeenCalled();
  });
  it('rejects oversized images and extra multipart fields', async () => {
    await upload(Buffer.alloc(MAX_USER_PHOTO_BYTES + 1)).expect(413);
    await request(app).patch('/api/chat-groups/4').field('profile', JSON.stringify({ name: 'New' })).field('avatarUrl', 'https://evil.test').attach('photo', png, 'photo.png').expect(400);
    expect(await fs.readdir(directory)).toEqual(before);
  });
  it('cleans the staged file when current management rights fail under the lock', async () => {
    mocks.updateProfile.mockRejectedValue(Object.assign(new Error('chatGroupManagementDenied'), { statusCode: 403 }));
    await upload().expect(403); expect(await fs.readdir(directory)).toEqual(before); expect(mocks.publish).not.toHaveBeenCalled();
  });
  it('rejects forged references and conflicting upload/removal requests', async () => {
    await request(app).patch('/api/chat-groups/4').send({ name: 'Team', removePhoto: true, avatarUrl: 'https://evil.test' }).expect(400);
    await request(app).patch('/api/chat-groups/4').field('profile', JSON.stringify({ name: 'Team', removePhoto: true })).attach('photo', png, 'photo.png').expect(400);
    expect(mocks.updateProfile).not.toHaveBeenCalled(); expect(await fs.readdir(directory)).toEqual(before);
  });
});
